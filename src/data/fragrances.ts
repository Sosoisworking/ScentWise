/*
Domain knowledge:
The fragrance pyramid:
- Top notes: first impression, last 5–15 min (citrus, light florals, herbs)
- Heart notes: core identity, last 1–4 hrs (rose, jasmine, spice, green)
- Base notes: longevity anchor, last 6+ hrs (oud, musk, vanilla, amber, sandalwood, cedarwood, vetiver, patchouli)
Longevity rules: SHORT (2–4 hrs) EDT citrus/aquatic; MEDIUM (4–6 hrs) EDP balanced; LONG (7+ hrs) Extrait/EDP heavy bases.
Families: Citrus fresh Spring/Summer; Floral romantic Spring/Summer; Woody grounding Fall/Winter; Oriental/Gourmand rich Fall/Winter; Aquatic clean Summer; Chypre sophisticated year-round.
Occasions: Date warm/sensual; Office clean/subtle; Party bold; Everyday versatile; Fresh crisp; Boozy indulgent; Luxury niche/statement; Casual comfortable; Gym airy/low projection; Vacation sunny/escape; Wedding polished romantic; Cozy intimate soft warmth; Black tie elegant formal; Brunch bright relaxed; Rainy Day clean musky comfort; Signature versatile memorable.
Pricing: CAD ranges are displayed for typical full-size Canadian retail. Sephora blocks automated scraping on many product pages, so embedded prices are maintained as CAD reference ranges and shopping buttons point to Sephora Canada plus Fragrancebuy search/product destinations.
Future schema: fragrances, fragrance_notes, fragrance_tags tables with normalized notes, seasons, occasions, and families.
*/

